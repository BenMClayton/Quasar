use crate::world::{Biome, TileKind, WorldId};
use macroquad::prelude::*;

#[derive(Clone, Copy)]
pub struct Palette {
    pub sky_top: Color,
    pub sky_bottom: Color,
    pub meadow: Color,
    pub forest: Color,
    pub wetland: Color,
    pub stone: Color,
    pub sand: Color,
    pub snow: Color,
    pub copper: Color,
    pub coal: Color,
    pub crystal: Color,
    pub cliff: Color,
    pub water: Color,
    pub accent: Color,
    pub glow: Color,
    pub highlight: Color,
    pub shadow: Color,
}

impl Palette {
    pub fn color_for(self, kind: TileKind, biome: Biome) -> Color {
        match kind {
            TileKind::Meadow => match biome {
                Biome::Wetland => self.wetland,
                Biome::Snow => self.snow,
                Biome::Ash => self.cliff,
                _ => self.meadow,
            },
            TileKind::Forest => self.forest,
            TileKind::Stone => self.stone,
            TileKind::CopperOre => self.copper,
            TileKind::CoalOre => self.coal,
            TileKind::Crystal => self.crystal,
            TileKind::Cliff => self.cliff,
            TileKind::Water => self.water,
            TileKind::Sand => self.sand,
            TileKind::Snow => self.snow,
        }
    }
}

